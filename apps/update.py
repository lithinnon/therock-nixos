"""Write versions/<VERSION>.nix: the hashes therock-nixos needs for a TheRock release.

usage: nix run .#update -- VERSION [gfx...] [--aotriton AOTRITON_VERSION] [--refresh]

AMD's wheel index publishes no hashes, so this downloads and hashes what is in
use: the arch-neutral wheels, GPU targets already in the manifest, this
machine's GPUs, and any gfx* named. AOTriton kernel images are hashed for the
families of those targets. Existing hashes are kept unless --refresh.
"""

import json
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

INDEX = "https://stable.repo.amd.com/rocm/whl-next"
AOTRITON = "https://github.com/ROCm/aotriton/releases/download"
ARCH_NEUTRAL = ["rocm-sdk-core", "rocm-sdk-libraries", "rocm-sdk-devel"]


def wheel_file(pname: str, version: str) -> str:
    return f"{pname.replace('-', '_')}-{version}-py3-none-linux_x86_64.whl"


def fetch(url: str, attempts: int = 5) -> str:
    for i in range(attempts):
        try:
            with urllib.request.urlopen(url, timeout=60) as r:
                return r.read().decode()
        except urllib.error.HTTPError:
            raise
        except (urllib.error.URLError, ConnectionError, TimeoutError) as e:
            if i == attempts - 1:
                sys.exit(f"update: {url}: {e}")
            time.sleep(2**i)


def published_targets(version: str) -> list[str]:
    names = re.findall(r'href="rocm-sdk-device-(gfx[0-9a-f]+)/', fetch(f"{INDEX}/"))

    def has(gfx):
        return wheel_file(f"rocm-sdk-device-{gfx}", version) in fetch(f"{INDEX}/rocm-sdk-device-{gfx}/")

    with ThreadPoolExecutor(max_workers=4) as pool:
        return [g for g, ok in zip(names, pool.map(has, names)) if ok]


def aotriton_families(version: str) -> list[str]:
    url = f"https://api.github.com/repos/ROCm/aotriton/releases/tags/{version}"
    try:
        assets = json.loads(fetch(url))["assets"]
    except urllib.error.HTTPError as e:
        sys.exit(f"update: AOTriton release {version} not found ({e.code})")
    pat = re.compile(rf"aotriton-{re.escape(version)}-images-amd-(gfx[0-9a-fx]+)\.tar\.gz")
    return sorted(m.group(1) for a in assets if (m := pat.fullmatch(a["name"])))


def family_of(gfx: str, families: list[str]) -> str | None:
    """Same rule as lib/default.nix: exact name, else gfxNNN + x."""
    if gfx in families:
        return gfx
    return next((f for f in families if f == gfx[:-1] + "x"), None)


def detect_gpus() -> list[str]:
    found = set()
    for props in Path("/sys/class/kfd/kfd/topology/nodes").glob("*/properties"):
        m = re.search(r"^gfx_target_version (\d+)$", props.read_text(), re.M)
        if m and int(m.group(1)):
            v = int(m.group(1))
            found.add(f"gfx{v // 10000}{(v // 100) % 100}{v % 100:x}")
    return sorted(found)


def prefetch(url: str) -> str:
    name = url.rsplit("/", 1)[1]  # same store name as fetchurl, so builds reuse it
    print(f"  hashing {name}", file=sys.stderr)
    b32 = subprocess.run(["nix-prefetch-url", "--name", name, url], check=True, capture_output=True, text=True).stdout.strip()
    return subprocess.run(
        ["nix", "hash", "convert", "--hash-algo", "sha256", "--to", "sri", b32], check=True, capture_output=True, text=True
    ).stdout.strip()


def load(path: Path) -> dict:
    if not path.exists():
        return {}
    out = subprocess.run(["nix", "eval", "--json", "--file", str(path)], check=True, capture_output=True, text=True)
    return json.loads(out.stdout)


def render(m: dict) -> str:
    def attrs(d, indent):
        pad = " " * indent
        return "\n".join(f'{pad}{k} = "{v}";' for k, v in sorted(d.items()))

    return f"""# TheRock {m['version']} release manifest: everything therock-nixos fetches for this version.
#
# Generated by `nix run .#update -- {m['version']}`; AMD's wheel index publishes no hashes.
# A GPU target missing from `devices` cannot be built until it is hashed here.
{{
  version = "{m['version']}";
  index = "{INDEX}";

  # Arch-neutral wheels, one store path each, shared by every GPU target.
  wheels = {{
{attrs(m['wheels'], 4)}
  }};

  # Per-GPU kernel wheels (rocm-sdk-device-<gfx>).
  devices = {{
{attrs(m['devices'], 4)}
  }};

  # Kernel images torch's AOTriton needs but AMD's torch wheels don't ship
  # (torch/lib/aotriton.images). Keyed by AOTriton's family name.
  aotriton = {{
    version = "{m['aotriton']['version']}";
    images = {{
{attrs(m['aotriton']['images'], 6)}
    }};
  }};
}}
"""


def main():
    args = sys.argv[1:]
    if not args or args[0] in ("-h", "--help"):
        sys.exit(__doc__)
    refresh = "--refresh" in args
    args = [a for a in args if a != "--refresh"]
    aot_version = None
    if "--aotriton" in args:
        i = args.index("--aotriton")
        aot_version = args[i + 1]
        del args[i : i + 2]
    version, named = args[0], args[1:]
    bad = [a for a in named if not re.fullmatch(r"gfx[0-9a-f]+", a)]
    if bad:
        sys.exit(f"update: not a gfx target: {' '.join(bad)}")

    root = Path(subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip() or ".")
    path = root / "versions" / f"{version}.nix"
    old = load(path)
    aot_version = aot_version or old.get("aotriton", {}).get("version")
    if not aot_version:
        sys.exit("update: new release: pass --aotriton <version> matching torch's libaotriton_v2.so")

    published = published_targets(version)
    if not published:
        sys.exit(f"update: TheRock {version} has no device wheels on {INDEX}")
    wanted = set(old.get("devices", {})) | set(named) | {g for g in detect_gpus() if g in published}
    missing = sorted(set(named) - set(published))
    if missing:
        sys.exit(f"update: no {version} device wheel for {' '.join(missing)} (published: {' '.join(published)})")
    families = aotriton_families(aot_version)

    keep = lambda section: {} if refresh else old.get(section, {})
    m = {
        "version": version,
        "wheels": dict(keep("wheels")),
        "devices": {k: v for k, v in keep("devices").items() if k in wanted},
        "aotriton": {"version": aot_version, "images": {} if refresh or aot_version != old.get("aotriton", {}).get("version") else dict(old["aotriton"]["images"])},
    }
    jobs = {}
    for p in ARCH_NEUTRAL:
        if p not in m["wheels"]:
            jobs[("wheels", p)] = f"{INDEX}/{p}/{wheel_file(p, version)}"
    for g in sorted(wanted):
        if g not in m["devices"]:
            jobs[("devices", g)] = f"{INDEX}/rocm-sdk-device-{g}/{wheel_file(f'rocm-sdk-device-{g}', version)}"
        fam = family_of(g, families)
        if fam and fam not in m["aotriton"]["images"]:
            jobs[("images", fam)] = f"{AOTRITON}/{aot_version}/aotriton-{aot_version}-images-amd-{fam}.tar.gz"

    print(f"TheRock {version}: targets {' '.join(sorted(wanted)) or '(none)'}; hashing {len(jobs)} files", file=sys.stderr)
    with ThreadPoolExecutor(max_workers=4) as pool:
        for (section, key), h in zip(jobs, pool.map(prefetch, jobs.values())):
            (m["aotriton"]["images"] if section == "images" else m[section])[key] = h

    path.parent.mkdir(exist_ok=True)
    path.write_text(render(m))
    print(f"wrote {path.relative_to(root)}", file=sys.stderr)


if __name__ == "__main__":
    main()
